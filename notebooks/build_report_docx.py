BODY_FONT = "맑은 고딕"
MONO_FONT = "D2Coding"          # 없으면 워드가 대체 — 구조도만 영향
BODY_PT = 11                    # 규격: 본문 11pt 고정


def set_font(run, name=BODY_FONT, size=BODY_PT, bold=False, color=None):
    run.font.name = name
    run.font.size = Pt(size)
    run.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)
    # 한글 글꼴은 eastAsia 를 따로 지정해야 적용된다.
    # rPr 이 아직 없을 수 있으므로 get_or_add 로 받는다.
    rpr = run._element.get_or_add_rPr()
    rf = rpr.get_or_add_rFonts()
    rf.set(qn("w:eastAsia"), name)
    rf.set(qn("w:ascii"), name)
    rf.set(qn("w:hAnsi"), name)


def para(doc, text="", size=BODY_PT, bold=False, style=None,
         align=None, space_after=6, font=BODY_FONT, color=None):
    p = doc.add_paragraph(style=style)
    if align is not None:
        p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    if text:
        set_font(p.add_run(text), font, size, bold, color)
    return p


def rich(doc, parts, space_after=6, size=BODY_PT):
    """parts = [(텍스트, 굵게), ...] — 한 문단 안에서 강조를 섞는다."""
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(space_after)
    for t, b in parts:
        set_font(p.add_run(t), BODY_FONT, size, b)
    return p


def h(doc, text, level):
    """제목. 크기는 자유 규격이므로 위계만 준다."""
    sizes = {1: 15, 2: 12.5, 3: 11.5}
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(14 if level == 1 else 9)
    p.paragraph_format.space_after = Pt(5)
    set_font(p.add_run(text), BODY_FONT, sizes[level], True,
             (0x1a, 0x3a, 0x5a) if level == 1 else None)
    return p


def bullet(doc, text, size=BODY_PT):
    p = doc.add_paragraph(style="List Bullet")
    p.paragraph_format.space_after = Pt(3)
    set_font(p.add_run(text), BODY_FONT, size)
    return p


def table(doc, rows, widths=None, size=9.5, header=True):
    """도표 내 글자 크기는 자유 규격이라 9.5pt 로 압축한다."""
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False          # 지정한 열 너비가 무시되지 않게 한다
    for i, row in enumerate(rows):
        for j, cell in enumerate(row):
            c = t.cell(i, j)
            c.text = ""
            p = c.paragraphs[0]
            p.paragraph_format.space_after = Pt(1)
            p.paragraph_format.space_before = Pt(1)
            txt = str(cell)
            bold = header and i == 0
            if txt.startswith("*"):          # *로 시작하면 강조
                txt, bold = txt[1:], True
            if j > 0 and txt and (txt[0].isdigit() or txt[0] in "+-"):
                p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            set_font(p.add_run(txt), BODY_FONT, size, bold)
            if widths:
                c.width = Cm(widths[j])
    doc.add_paragraph().paragraph_format.space_after = Pt(4)
    return t


def mono(doc, lines, size=8.5):
    """구조도. 고정폭으로 그린다."""
    for ln in lines:
        p = doc.add_paragraph()
        p.paragraph_format.space_after = Pt(0)
        p.paragraph_format.space_before = Pt(0)
        p.paragraph_format.line_spacing = 1.0
        set_font(p.add_run(ln), MONO_FONT, size)


def note(doc, text, size=9.5):
    """근거·주석 줄."""
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(8)
    p.paragraph_format.left_indent = Cm(0.4)
    set_font(p.add_run(text), BODY_FONT, size, False, (0x44, 0x44, 0x44))
    return p


